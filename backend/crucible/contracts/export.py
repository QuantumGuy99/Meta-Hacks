"""Generate frontend/src/types/contracts.ts from the contract models (PLAN §7.6).

`python -m crucible.contracts.export` writes the file; `--check` exits 1 if it's out of date (for CI).
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from crucible.contracts import coding, common, defense, events, report, ws

REPO_ROOT = Path(__file__).resolve().parents[3]
OUTPUT = REPO_ROOT / "frontend" / "src" / "types" / "contracts.ts"
JSON2TS = "json-schema-to-typescript@16.0.0"  # pinned: a new version could reformat the whole file
HEADER = "// Generated by `make contracts` (backend/crucible/contracts/export.py). Do not edit by hand.\n"

# What the frontend reads or sends at the top level. Nested models (EditorEvent, Finding, …) come along.
TOP_LEVEL: dict[str, Any] = {
    "ClientMessage": ws.ClientMessage,
    "ServerMessage": ws.ServerMessage,
    "SessionConfig": common.SessionConfig,
    "Session": common.Session,
    "Health": common.Health,
    "ApiError": common.ApiError,
    "ReportPending": common.ReportPending,
    "ProblemSummary": coding.ProblemSummary,
    "ProblemPublic": coding.ProblemPublic,
    "Project": defense.Project,
    "ProjectSource": defense.ProjectSource,
    "Report": report.Report,
    # timeline payloads the replay reads (GET /api/sessions/{id}/timeline)
    "TimelineEvent": events.TimelineEvent,
    "PhaseChange": events.PhaseChange,
    "SystemNote": events.SystemNote,
    "Analysis": coding.Analysis,
    "AuditResult": defense.AuditResult,
}

# Schema keywords whose values map names to schemas, so their keys are names, not keywords.
_NAMED_SCHEMAS = ("properties", "definitions", "$defs", "patternProperties")
_NOT_SCHEMAS = ("default", "const", "enum", "examples", "required")


def build_schema() -> dict[str, Any]:
    """One JSON Schema whose definitions hold every top-level type, named after its Python type."""
    definitions: dict[str, Any] = {}
    for name, tp in TOP_LEVEL.items():
        schema = TypeAdapter(tp).json_schema(ref_template="#/definitions/{model}")
        definitions.update(schema.pop("$defs", {}))
        definitions[name] = schema
    for name, schema in definitions.items():
        _strip_titles(schema)
        schema["title"] = name
    return {
        "title": "CrucibleContracts",
        "type": "object",
        "properties": {name: {"$ref": f"#/definitions/{name}"} for name in TOP_LEVEL},
        "required": list(TOP_LEVEL),
        "additionalProperties": False,
        "definitions": dict(sorted(definitions.items())),
    }


def render() -> str:
    schema = json.dumps(build_schema(), indent=2)
    result = subprocess.run(
        ["pnpm", "--silent", "dlx", JSON2TS, "--unknownAny", "--unreachableDefinitions"],
        input=schema,
        capture_output=True,
        text=True,
        check=True,
        cwd=REPO_ROOT,
        encoding="utf-8",
    )
    return HEADER + result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if contracts.ts is out of date")
    args = parser.parse_args()
    rendered = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            print(f"{OUTPUT.relative_to(REPO_ROOT)} is out of date: run `make contracts`", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


def _strip_titles(node: Any) -> None:
    # Pydantic titles every field ("Range Offset"); json2ts would turn each into its own type alias.
    if isinstance(node, list):
        for item in node:
            _strip_titles(item)
    elif isinstance(node, dict):
        node.pop("title", None)
        for key, value in node.items():
            if key in _NAMED_SCHEMAS and isinstance(value, dict):
                for sub in value.values():
                    _strip_titles(sub)
            elif key not in _NOT_SCHEMAS:
                _strip_titles(value)


if __name__ == "__main__":
    sys.exit(main())
